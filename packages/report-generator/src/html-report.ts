import { AuditReportData } from "./types.js";

function getScoreColorHex(score?: number | null): string {
  if (score == null) return "#71717a";
  if (score >= 90) return "#10b981";
  if (score >= 50) return "#f59e0b";
  return "#f43f5e";
}

/**
 * Generates an executive, print-ready, high-resolution HTML/PDF document from audit telemetry.
 */
export function generateExecutiveHTMLReport(report: AuditReportData): string {
  const whiteLabel = report.whiteLabel || {};
  const companyName = whiteLabel.companyName || "SpeedPilot Intelligence";
  const primaryColor = whiteLabel.primaryColor || "#0f172a";
  const reportFooter = whiteLabel.reportFooter || `Generated by ${companyName} on ${new Date(report.createdAt).toLocaleDateString()}`;

  // Compute aggregate averages
  const validScores = report.executions
    .map((e) => e.scores?.performance)
    .filter((s): s is number => s != null);

  const avgPerf = validScores.length > 0
    ? Math.round(validScores.reduce((a, b) => a + b, 0) / validScores.length)
    : "—";

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>${report.reportTitle} — ${companyName}</title>
  <style>
    @page {
      size: A4;
      margin: 1.5cm;
    }
    * { box-sizing: border-box; margin: 0; padding: 0; }
    body {
      font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
      color: #1e293b;
      background: #ffffff;
      line-height: 1.5;
      font-size: 13px;
    }
    .container {
      max-width: 800px;
      margin: 0 auto;
      padding: 24px;
    }
    .header {
      display: flex;
      justify-content: space-between;
      align-items: center;
      border-bottom: 2px solid #e2e8f0;
      padding-bottom: 16px;
      margin-bottom: 24px;
    }
    .brand-title {
      font-size: 20px;
      font-weight: 800;
      color: ${primaryColor};
    }
    .report-meta {
      font-size: 11px;
      color: #64748b;
      text-align: right;
    }
    .badge {
      display: inline-block;
      padding: 2px 8px;
      border-radius: 9999px;
      font-size: 11px;
      font-weight: 600;
    }
    .summary-grid {
      display: grid;
      grid-template-columns: repeat(4, 1fr);
      gap: 12px;
      margin-bottom: 28px;
    }
    .card {
      border: 1px solid #e2e8f0;
      border-radius: 8px;
      padding: 12px;
      background: #f8fafc;
    }
    .card-title {
      font-size: 11px;
      font-weight: 600;
      color: #64748b;
      text-transform: uppercase;
      letter-spacing: 0.05em;
    }
    .card-value {
      font-size: 24px;
      font-weight: 800;
      font-family: ui-monospace, SFMono-Regular, Menlo, Monaco, Consolas, monospace;
      margin-top: 4px;
    }
    .section-title {
      font-size: 15px;
      font-weight: 700;
      color: #0f172a;
      border-bottom: 1px solid #e2e8f0;
      padding-bottom: 6px;
      margin-top: 24px;
      margin-bottom: 14px;
    }
    table {
      width: 100%;
      border-collapse: collapse;
      font-size: 12px;
      margin-bottom: 24px;
    }
    th, td {
      padding: 8px 10px;
      border-bottom: 1px solid #e2e8f0;
      text-align: left;
    }
    th {
      background: #f1f5f9;
      color: #475569;
      font-weight: 600;
    }
    .code-box {
      background: #0f172a;
      color: #f8fafc;
      font-family: ui-monospace, monospace;
      font-size: 11px;
      padding: 12px;
      border-radius: 6px;
      overflow-x: auto;
      margin-top: 8px;
    }
    .footer {
      border-top: 1px solid #e2e8f0;
      padding-top: 16px;
      margin-top: 40px;
      font-size: 11px;
      color: #94a3b8;
      text-align: center;
    }
    @media print {
      body { background: transparent; }
      .page-break { page-break-before: always; }
    }
  </style>
</head>
<body>
  <div class="container">
    <!-- Header -->
    <div class="header">
      <div>
        <div class="brand-title">${companyName}</div>
        <div style="font-size: 13px; font-weight: 600; color: #334155; margin-top: 2px;">
          Website Performance & Core Web Vitals Audit Report
        </div>
        <div style="font-size: 11px; color: #64748b;">
          Target: ${report.projectName} (${report.primaryDomain})
        </div>
      </div>
      <div class="report-meta">
        <div><strong>Date:</strong> ${new Date(report.createdAt).toLocaleDateString()}</div>
        <div><strong>Device:</strong> ${report.deviceMode}</div>
        <div><strong>Audited URLs:</strong> ${report.executions.length}</div>
      </div>
    </div>

    <!-- Executive Summary Cards -->
    <div class="summary-grid">
      <div class="card">
        <div class="card-title">Average Performance</div>
        <div class="card-value" style="color: ${getScoreColorHex(typeof avgPerf === "number" ? avgPerf : null)};">
          ${avgPerf}
        </div>
      </div>
      <div class="card">
        <div class="card-title">Monitored Pages</div>
        <div class="card-value">${report.executions.length}</div>
      </div>
      <div class="card">
        <div class="card-title">Total Opportunities</div>
        <div class="card-value">
          ${report.executions.reduce((acc, curr) => acc + (curr.issues?.length || 0), 0)}
        </div>
      </div>
      <div class="card">
        <div class="card-title">Audit Engine</div>
        <div class="card-value" style="font-size: 16px; margin-top: 8px;">PSI + CrUX</div>
      </div>
    </div>

    <!-- Results Table -->
    <div class="section-title">Audited Page Benchmarks</div>
    <table>
      <thead>
        <tr>
          <th>URL</th>
          <th>Device</th>
          <th style="text-align: center;">Performance</th>
          <th style="text-align: center;">SEO</th>
          <th style="text-align: right;">LCP (Lab)</th>
          <th style="text-align: right;">TBT (Lab)</th>
          <th style="text-align: center;">INP (Field)</th>
        </tr>
      </thead>
      <tbody>
        ${report.executions.map((e) => `
          <tr>
            <td style="font-family: monospace; max-width: 250px; overflow: hidden; text-overflow: ellipsis; white-space: nowrap;">
              ${e.url}
            </td>
            <td>${e.device}</td>
            <td style="text-align: center; font-weight: bold; color: ${getScoreColorHex(e.scores?.performance)};">
              ${e.scores?.performance ?? "—"}
            </td>
            <td style="text-align: center; font-weight: bold; color: ${getScoreColorHex(e.scores?.seo)};">
              ${e.scores?.seo ?? "—"}
            </td>
            <td style="text-align: right; font-family: monospace;">
              ${e.labMetrics?.lcpMs ? `${e.labMetrics.lcpMs}ms` : "—"}
            </td>
            <td style="text-align: right; font-family: monospace;">
              ${e.labMetrics?.tbtMs ? `${e.labMetrics.tbtMs}ms` : "—"}
            </td>
            <td style="text-align: center; font-family: monospace;">
              ${e.crux?.inpValueMs ? `${e.crux.inpValueMs}ms` : "<span style='color: #94a3b8; font-style: italic;'>No Data</span>"}
            </td>
          </tr>
        `).join("")}
      </tbody>
    </table>

    <!-- Prioritized AI Remediation Highlights -->
    <div class="section-title">Prioritized AI Fix Recommendations</div>
    <div style="display: flex; flex-direction: column; gap: 16px;">
      ${report.executions.flatMap((e) => (e.issues || []).slice(0, 2).map((issue) => `
        <div style="border: 1px solid #e2e8f0; border-radius: 8px; padding: 14px; background: #ffffff;">
          <div style="display: flex; justify-content: space-between; align-items: center; margin-bottom: 6px;">
            <div style="font-weight: 700; font-size: 13px;">${issue.title}</div>
            <span style="font-size: 10px; font-weight: 700; text-transform: uppercase; background: #fef3c7; color: #b45309; padding: 2px 6px; border-radius: 4px;">
              ${issue.severity}
            </span>
          </div>
          <div style="font-size: 11px; color: #64748b; font-family: monospace; margin-bottom: 8px;">
            Target URL: ${e.url}
          </div>
          ${issue.displayValue ? `<div style="font-size: 11px; color: #10b981; font-weight: 600; margin-bottom: 8px;">${issue.displayValue}</div>` : ""}
          <div style="font-size: 12px; color: #334155; margin-bottom: 8px;">
            <strong>Marketer View:</strong> ${issue.recommendation?.explanationMarketer || "Audit opportunity requires optimization to improve user experience."}
          </div>
          ${issue.recommendation?.remediationCodeSnippet ? `
            <div class="code-box">
              <pre>${issue.recommendation.remediationCodeSnippet}</pre>
            </div>
          ` : ""}
        </div>
      `)).slice(0, 5).join("")}
    </div>

    <!-- Footer -->
    <div class="footer">
      ${reportFooter}
      ${whiteLabel.hidePoweredBy ? "" : " • Powered by SpeedPilot Intelligence"}
    </div>
  </div>
</body>
</html>`;
}
